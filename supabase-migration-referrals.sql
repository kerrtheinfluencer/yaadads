-- 10. RLS policies + grants
--     Writes happen ONLY inside the security-definer functions above, so
--     public/anonymous clients get read-only access (leaderboard + their
--     own tracking rows).
-- ══════════════════════════════════════════════════════════════════════
alter table public.referral_events enable row level security;
alter table public.referral_leads   enable row level security;
alter table public.weekly_winners   enable row level security;

-- Leaderboard read (anon + auth) — column-granted so email/phone stay private.
grant select (id, name, yaad_points, total_referrals, referrals_this_week,
              last_week_winner, best_week_rank, referral_code)
       on public.profiles to anon, authenticated;

drop policy if exists "anyone reads profiles leaderboard" on public.profiles;
create policy "anyone reads profiles leaderboard" on public.profiles
  for select using (true);

-- Tracking rows: members can see their OWN referral events + email leads.
drop policy if exists "owner reads own referral events" on public.referral_events;
create policy "owner reads own referral events" on public.referral_events
  for select using (referrer_id = auth.uid());

drop policy if exists "owner reads own referral leads" on public.referral_leads;
create policy "owner reads own referral leads" on public.referral_leads
  for select using (referrer_id = auth.uid());

-- Past weekly winners are public (that's the leaderboard history).
drop policy if exists "anyone views weekly winners" on public.weekly_winners;
create policy "anyone views weekly winners" on public.weekly_winners
  for select using (true);

